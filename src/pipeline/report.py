"""Render a pipeline run as 1 readable Markdown report.

The report puts what a person acts on first (use case, action plan, 1-pager, MVP idea), then
the company snapshot and ranked hypotheses, and ends with a Sources section that resolves
every cited ID: evidence IDs (e1, e2, ...) to their quote and URL, and recommendation IDs
(r1, r2, ...) to the specialist advice they stand for.

It only formats the JSON results that the agents already validated; it adds no new claims.

  ventureos-report runs/linear-pm.json --strategy runs/linear-gtm.json \\
      --research runs/linear-research.json --output runs/linear-report.md
"""

import argparse
import json
from pathlib import Path
from typing import Any

Json = dict[str, Any]

SNAPSHOT_LABELS = {
    "mission": "Mission", "vision": "Vision", "problem": "Problem",
    "target_market": "Target market", "icp": "Ideal customer (ICP)", "product": "Product",
    "client_value": "Client value", "market_brief": "Market brief",
    "competitive_landscape": "Competition",
}
AGENT_LABELS = {"market_analysis": "Market analyst", "competitive_strategy": "Competitive strategist",
                "challenger_salesman": "Challenger salesperson"}


def _text(value: object) -> str:
    """1 line of plain text: collapses newlines so a value cannot break the Markdown layout."""
    return " ".join(str(value or "").split())


def _cell(value: object) -> str:
    return _text(value).replace("|", "\\|")


def _ids(ids: object) -> str:
    items = [str(item) for item in ids or []] if isinstance(ids, list) else []
    return f" `{', '.join(items)}`" if items else ""


def _link(url: str) -> str:
    url = _text(url)
    return f"<{url}>" if url.startswith(("https://", "http://")) else _cell(url)


def _header(name: str, website: str, statuses: list[str]) -> list[str]:
    out = [f"# VentureOS report: {_text(name)}", ""]
    meta = [_link(website)] if website else []
    out += [" · ".join(meta + statuses), ""] if meta or statuses else []
    out += ["> Generated by [VentureOS](https://github.com/efolley/Venture-OS). It proposes; a "
            "person decides. IDs in `backticks` point to the Sources section at the end. "
            "_(hypothesis)_ marks advice that no source directly states. Review before sharing.",
            ""]
    return out


def _use_case(use_case: Json) -> list[str]:
    out = ["## Use case", "", f"> **{_text(use_case['statement'])}**", ""]
    for key, label in (("icp", "Ideal customer"), ("core_problem", "Core problem"),
                       ("mvp_solution", "MVP solution")):
        part = use_case.get(key) or {}
        out.append(f"- **{label}:** {_text(part.get('text'))}{_ids(part.get('based_on'))}")
    out.append(f"- **Why:** {_text(use_case.get('why'))}{_ids(use_case.get('why_based_on'))}")
    out.append(f"- **Key assumption to test:** {_text(use_case.get('key_assumption'))}")
    for alternative in use_case.get("alternatives") or []:
        out.append(f"- **Not chosen:** {_text(alternative.get('statement'))} "
                   f"_({_text(alternative.get('why_not'))})_")
    return out + [""]


def _action_plan(actions: list[Json]) -> list[str]:
    out = ["## Action plan", ""]
    for number, action in enumerate(actions, start=1):
        tags = " · ".join(_text(action.get(key)) for key in ("purpose", "horizon", "owner")
                          if action.get(key))
        out.append(f"{number}. **{_text(action.get('title'))}** _(P{action.get('priority', '?')} · "
                   f"{tags})_  ")
        out.append(f"   {_text(action.get('description'))}{_ids(action.get('based_on'))}  ")
        out.append(f"   _Success metric:_ {_text(action.get('success_metric'))}")
    return out + [""]


def _one_pager(brief: Json) -> list[str]:
    out = ["## 1-pager", "", f"### {_text(brief.get('headline'))}", "",
           f"**Problem.** {_text(brief.get('problem'))}", "",
           f"**What we propose.** {_text(brief.get('value_proposition'))}", "",
           f"**For.** {_text(brief.get('target_customer'))}", "", "**Key points**", ""]
    out += [f"- {_text(point)}" for point in brief.get("key_points") or []]
    out += ["", "**Proof points**", ""]
    out += [f"- {_text(point)}" for point in brief.get("proof_points") or []]
    out += ["", f"**Next step.** {_text(brief.get('call_to_action'))}", ""]
    return out


def _mvp_idea(brief: Json) -> list[str]:
    out = ["## MVP idea", "", "_A proposal of what to build. Nothing has been built._", "",
           f"- **Goal:** {_text(brief.get('product_goal'))}",
           f"- **Target user:** {_text(brief.get('target_user'))}",
           f"- **Core job:** {_text(brief.get('core_job'))}", "", "**Must-have features**", ""]
    out += [f"- **{_text(feature.get('name'))}:** {_text(feature.get('why'))}"
            f"{_ids(feature.get('based_on'))}" for feature in brief.get("must_have_features") or []]
    out += ["", "**Out of scope**", ""]
    out += [f"- {_text(item)}" for item in brief.get("out_of_scope") or []]
    out += ["", "**Success criteria**", ""]
    out += [f"- {_text(item)}" for item in brief.get("success_criteria") or []]
    if brief.get("demo_scenario"):
        out += ["", f"**How a user tries it.** {_text(brief['demo_scenario'])}"]
    return out + [""]


def _hitl(pm: Json) -> list[str]:
    baseline = pm.get("baseline") or {}
    missing = ", ".join(_text(item) for item in baseline.get("missing") or [])
    out = ["## Waiting for a person", ""]
    if missing:
        out.append(f"The strategy does not cover the basics yet. Missing: {missing}.")
    hitl = pm.get("hitl") or {}
    if hitl.get("question"):
        out += ["", f"**Question:** {_text(hitl['question'])}"]
    request = pm.get("research_request") or {}
    if request.get("gaps"):
        out += ["", "**Sent back to Research.** Gaps to collect: "
                + ", ".join(_text(gap) for gap in request["gaps"])]
    return out + [""]


def _snapshot(strategy: Json) -> list[str]:
    snapshot = strategy.get("snapshot") or {}
    lines = snapshot.get("lines") or {}
    out = ["## Company snapshot", ""]
    for key, label in SNAPSHOT_LABELS.items():
        line = lines.get(key) or {}
        if line.get("status") == "found":
            basis = " _(hypothesis)_" if line.get("basis") == "hypothesis" else ""
            ids = [*(line.get("evidence_ids") or []), *(line.get("recommendation_ids") or [])]
            out.append(f"- **{label}:** {_text(line.get('text'))}{basis}{_ids(ids)}")
        else:
            out.append(f"- **{label}:** _unknown_")
    return out + [""]


def _hypotheses(strategy: Json) -> list[str]:
    items = sorted((item for item in strategy.get("recommendations") or []
                    if item.get("agent") == "competitive_strategy" and item.get("rank")),
                   key=lambda item: item["rank"])
    if not items:
        return []
    out = ["## Ranked competitive hypotheses", "",
           "Code scores each hypothesis from 4 to 20 (pain, gap size, competitor weakness, fit).", "",
           "| Rank | Score | Hypothesis | Validate by asking |", "| --- | --- | --- | --- |"]
    for item in items:
        out.append(f"| {item['rank']} | {item.get('score', '')}/20 | **{_cell(item.get('title'))}** "
                   f"`{_cell(item.get('id'))}` | {_cell(item.get('validation_question'))} |")
    return out + [""]


def _gaps(strategy: Json) -> list[str]:
    gaps = strategy.get("gaps") or []
    if not gaps:
        return []
    return ["## Known gaps", "", *[f"- {_text(gap)}" for gap in gaps], ""]


def _sources(strategy: Json | None, research: Json | None) -> list[str]:
    out: list[str] = []
    recommendations = (strategy or {}).get("recommendations") or []
    evidence = (research or {}).get("evidence") or []
    if not recommendations and not evidence:
        return out
    out += ["## Sources", ""]
    if evidence:
        out += ["### Evidence", "", "Each fact quotes its source word for word.", "",
                "| ID | Fact | Quote | Source |", "| --- | --- | --- | --- |"]
        for item in evidence:
            label = _cell(item.get("statement"))
            if item.get("basis") and item.get("basis") != "fact":
                label += f" _({_cell(item['basis'])})_"
            out.append(f"| `{_cell(item.get('id'))}` | {label} | \"{_cell(item.get('excerpt'))}\" | "
                       f"{_link(str(item.get('url') or ''))} |")
        out.append("")
    if recommendations:
        out += ["### Specialist recommendations", "",
                "| ID | Specialist | Recommendation | Basis | Cites |", "| --- | --- | --- | --- | --- |"]
        for item in recommendations:
            agent = AGENT_LABELS.get(item.get("agent"), _cell(item.get("agent")))
            out.append(f"| `{_cell(item.get('id'))}` | {agent} | **{_cell(item.get('title'))}**: "
                       f"{_cell(item.get('recommendation'))} | {_cell(item.get('basis'))} | "
                       f"{_cell(', '.join(item.get('evidence_ids') or []))} |")
        out.append("")
    return out


def report_markdown(pm: Json | None = None, strategy: Json | None = None,
                    research: Json | None = None) -> str:
    """1 Markdown report from any of the 3 results; the PM result comes first when present."""
    source = pm or strategy or research
    if source is None:
        raise ValueError("Give at least 1 of the PM result, strategy pack, or evidence pack.")
    company = source.get("company") or {}
    statuses = [f"{label} **{_text(value['status'])}**" for label, value in
                (("research", research), ("strategy", strategy), ("plan", pm))
                if value and value.get("status")]
    out = _header(str(company.get("name") or "company"), str(company.get("website") or ""),
                  statuses)
    if pm:
        if pm.get("status") in {"hitl_required", "research_requested"}:
            out += _hitl(pm)
        if pm.get("use_case"):
            out += _use_case(pm["use_case"])
        if pm.get("action_plan"):
            out += _action_plan(pm["action_plan"])
        if pm.get("one_pager"):
            out += _one_pager(pm["one_pager"])
        if pm.get("mvp_idea"):
            out += _mvp_idea(pm["mvp_idea"])
    if strategy:
        out += _snapshot(strategy) + _hypotheses(strategy) + _gaps(strategy)
    out += _sources(strategy, research)
    return "\n".join(out).rstrip() + "\n"


def _load(path: Path | None) -> Json | None:
    return json.loads(path.read_text(encoding="utf-8")) if path else None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="ventureos-report", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("pm", type=Path, nargs="?", help="PM result JSON")
    parser.add_argument("--strategy", type=Path, help="GTM strategy pack JSON")
    parser.add_argument("--research", type=Path, help="Research evidence pack JSON")
    parser.add_argument("--output", type=Path, help="Markdown file (default: print)")
    args = parser.parse_args(argv)
    try:
        text = report_markdown(_load(args.pm), _load(args.strategy), _load(args.research))
    except (OSError, ValueError) as error:
        parser.error(str(error))
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
        print(f"Report: {args.output}")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
